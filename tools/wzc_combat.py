def fix_effects(N):
    """解析器把“关系下降/警戒上升”之类读成了 set … true，这里改成数值增减。"""
    from wzc_patches import walk_choices
    for n in N.values():
        for c in walk_choices(n):
            for src in (c, c.get("success") or {}, c.get("fail") or {}):
                for e in src.get("effects", []):
                    if e.get("op") == "set" and e.get("v") is True and (str(e["k"]).startswith("rel.") or e["k"] in ("alarm_town", "alarm_mine")):
                        e["op"] = "add"
                        e["v"] = -1 if e["k"].startswith("rel.") else 1
    for c in walk_choices(N["L-PRO-06"]):
        if c["label"].startswith("允许杀死"):
            c["effects"].append(setf("kael_lethal"))
