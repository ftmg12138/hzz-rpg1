def INNER(t): return {"t": "inner", "text": t}
def H(t): return {"t": "h", "text": t}
def CK(stats, dc=13, combat=False, **kw):
    d = {"stats": stats, "dc": dc}
    if combat: d["combat"] = True
    d.update(kw)
    return d
R = "__RETURN__"

def chk(cid, label, nxt, stats, dc, ok, bad, ok_fx=None, bad_fx=None, ok_next=None, bad_next=None, combat=False, result=None, **kw):
    c = C(cid, label, nxt, result or [], [], check=CK(stats, dc, combat, **{k: kw.pop(k) for k in list(kw) if k in ("adv_if", "auto_if", "auto_text")}),
          success=branch(ok, ok_fx, ok_next), fail=branch(bad, bad_fx, bad_next), **kw)
    return c

